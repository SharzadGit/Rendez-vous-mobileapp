"""Offline oracle: Python 3, shapely==2.1.2. Never contacts ORS.

Run from repository root after installing Shapely in a separate environment.
Coordinates are arbitrary analytic test coordinates, not measured road data.
"""
import json
from pathlib import Path
import shapely
from shapely.geometry import Polygon, MultiPolygon, box, mapping


def area_geometry(g):
    if g.is_empty or g.area == 0:
        return None
    if g.geom_type in ("Polygon", "MultiPolygon"):
        return mapping(g)
    polygons = []
    for child in g.geoms:
        if child.geom_type == "Polygon":
            polygons.append(child)
        elif child.geom_type == "MultiPolygon":
            polygons.extend(child.geoms)
    return mapping(MultiPolygon(polygons)) if polygons else None


outer = box(0, 0, 10, 10)
donut = Polygon(outer.exterior.coords, [box(3, 3, 7, 7).exterior.coords])
u_shape = Polygon([(0, 0), (6, 0), (6, 6), (4, 6), (4, 2), (2, 2), (2, 6), (0, 6)])
cases = [
    ("two rectangles", [box(0, 0, 4, 4), box(2, 1, 6, 3)]),  # [2,1]-[4,3], area 4
    ("three partial overlaps", [box(0, 0, 6, 6), box(2, 1, 8, 5), box(1, 3, 5, 8)]),  # area 6
    ("disjoint", [box(0, 0, 1, 1), box(2, 0, 3, 1)]),
    ("identical", [outer, outer]),
    ("contained", [outer, box(1, 1, 2, 2)]),
    ("concave split", [u_shape, box(-1, 3, 7, 5)]),  # two disconnected 2x2 rectangles
    ("hole preserved", [donut, box(1, 1, 9, 9)]),  # area 64-16=48
    ("inside hole is empty", [donut, box(4, 4, 6, 6)]),
    ("clip opens hole", [donut, box(0, 4, 5, 8)]),
    ("multipolygon", [MultiPolygon([box(0, 0, 2, 2), box(4, 0, 6, 2)]), box(1, -1, 5, 3)]),
    ("island inside hole", [MultiPolygon([donut, box(4, 4, 6, 6)]), box(1, 1, 9, 9)]),
    ("edge contact", [box(0, 0, 1, 1), box(1, 0, 2, 1)]),
    ("point contact", [box(0, 0, 1, 1), box(1, 1, 2, 2)]),
    ("area and boundary components", [MultiPolygon([box(0, 0, 2, 2), box(4, 0, 6, 2)]),
                                       MultiPolygon([box(1, 1, 3, 3), box(6, 0, 7, 2)])]),
    ("sloped edges", [Polygon([(0, 0), (4, 0), (0, 4)]), box(1, 1, 4, 4)]),  # area 2
    ("one grid cell sliver", [box(0, 0, 1, 1), box(0.9999, 0, 2, 1)]),  # maps to 1e-7 deg wide
]
for n in (3, 5, 10, 20):
    cases.append((f"{n} participants", [box(i * 0.1, i * 0.1, 10 - i * 0.1, 10 - i * 0.1)
                                       for i in range(n)]))
fixtures = []
for name, inputs in cases:
    assert all(g.is_valid for g in inputs)
    result = inputs[0]
    for other in inputs[1:]:
        result = result.intersection(other)
    fixtures.append(dict(name=name, inputs=[mapping(g) for g in inputs],
                         expected=area_geometry(result), area=result.area))
data = dict(shapely=shapely.__version__, geos=shapely.geos_version_string, fixtures=fixtures)
text = json.dumps(data, separators=(",", ":"), sort_keys=True)
Path("test/fixtures/intersection_fixtures.dart").write_text(
    "// Generated by tool/generate_intersection_fixtures.py; do not edit.\n"
    "// Synthetic analytic geometry fixtures, not road-network observations.\n"
    "const intersectionFixturesJson =\n    r'''" + text + "''';\n")
print(f"Generated {len(fixtures)} oracle fixtures with Shapely {shapely.__version__}, GEOS {shapely.geos_version_string}")
